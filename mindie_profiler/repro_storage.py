"""Short-root artifact staging and resolvable reproducer handles.

[Role]
  Persist immutable script/manifest pairs and resolve their sha256 identifiers.

[Invariants]
  * The default root is ``/tmp/mprof`` or an ASCII MINDIE_REPRO_SHORT_ROOT <= 48.
  * A registered pair is immutable; a conflict is blocked.
  * Protected inodes are tracked by ``(st_dev, st_ino)``; symlink/hardlink
    aliases of a live or historical script/manifest are refused before writes.
  * Writes use an ``O_EXCL|O_NOFOLLOW`` sibling, then exclusive ``os.link`` for
    CAS or ``os.replace`` for caller/index leaves; rollback parks exact inodes.
  * Staging walks each component with ``lstat``; symlinks fail closed.
  * Delivered pairs are re-opened with ``O_RDONLY|O_NOFOLLOW`` and byte-hashed.
  * Invalid/refused indexes mark delivery_failed/index_persistence_failed
    with index_persisted=False; the staged pair and old index bytes are kept.

[Timeouts & Locks]
  A shared process-local commit/rollback RLock; no lock spans verification.

[Side-Effect Policy]
  Writes only the short root or the explicitly requested output path.
"""

from __future__ import annotations
import contextlib
import errno
import hashlib
import json
import os
from pathlib import Path
import stat
from typing import Any
from .repro_atomic_io import ( _COMMITTED_INODES as _PROTECTED_INODES, _OWNERSHIP_LOCK as _LOCK,
    _cleanup_scope, _retry_cleanup, _unlink_owned_path, ensure_directory, inode_of as _inode_of,
    path_lexists, read_regular_bytes as _read_regular_bytes, safe_write_bytes,
)
SHORT_ROOT_DEFAULT = "/tmp/mprof"
SHORT_ROOT_MAX = 48
_INDEX_NAME = "index.json"
_REGISTRY: dict[str, dict[str, Any]] = {}
_SLOTS: set[Path] = set()
_ROOTS: set[Path] = set()
_CAS_SCRIPT_MARKER = b"single-op reproducer generated by mindie-profiler"
_CAS_MANIFEST_KEYS = (b'"repro_sha256"', b'"script_sha256"')
def short_root() -> Path:
    """Bounded ASCII root independent of a long platform ``gettempdir()``."""
    configured = str(os.environ.get("MINDIE_REPRO_SHORT_ROOT") or "").strip()
    if (configured and configured.isascii()
            and len(configured.encode("utf-8")) <= SHORT_ROOT_MAX):
        root = Path(configured)
    else:
        root = Path(SHORT_ROOT_DEFAULT)
    resolved = _resolved(root)
    if resolved is not None:
        with _LOCK:
            _ROOTS.add(resolved)
    return root
def _known_roots() -> set[Path]:
    current = short_root()
    with _LOCK:
        roots = set(_ROOTS)
    roots.add(_resolved(current) or current)
    return roots
def artifact_id(script: str) -> str:
    return "sha256:" + hashlib.sha256(script.encode("utf-8")).hexdigest()
def _sha256(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()
def _encode_pair(script: str, manifest: dict[str, Any]) -> tuple[bytes, bytes]:
    script_bytes = script.encode("utf-8")
    manifest_bytes = (json.dumps(manifest, indent=2, sort_keys=True,
                                 ensure_ascii=False) + "\n").encode("utf-8")
    return script_bytes, manifest_bytes
def _readable(path: Any) -> bool:
    data = _read_regular_bytes(path)
    try:
        return data is not None and bool(data.decode("utf-8"))
    except UnicodeError:
        return False
def _remember_inodes(*paths: Any) -> None:
    with _LOCK:
        found = {inode for inode in (_inode_of(path) for path in paths) if inode}
        if len(found) == len(paths):
            _PROTECTED_INODES.update(found)
def _scan_pair_inodes(directory: Path, found: set[tuple[int, int]]) -> None:
    for name in ("repro.py", "manifest.json"):
        inode = _inode_of(directory / name)
        if inode is not None:
            found.add(inode)
def _protected_inodes() -> set[tuple[int, int]]:
    index_path = _index_path()
    index_abs = os.path.abspath(index_path)
    with _LOCK:
        found = set(_PROTECTED_INODES)
        slots = set(_SLOTS)
        entries = list(_REGISTRY.values())
    pair = set(found)
    for entry in entries:
        for key in ("artifact_path", "manifest_path"):
            value = entry.get(key)
            if value and (inode := _inode_of(value)) is not None:
                found.add(inode)
                pair.add(inode)
    for slot in slots:
        before = set(found)
        _scan_pair_inodes(slot, found)
        pair.update(found - before)
    for root in _known_roots():
        try:
            children = list(root.iterdir())
        except TimeoutError: raise
        except OSError:
            children = []
        for child in children:
            try:
                info = os.lstat(child)
            except TimeoutError: raise
            except OSError:
                continue
            if stat.S_ISDIR(info.st_mode):
                before = set(found)
                _scan_pair_inodes(child, found)
                pair.update(found - before)
            elif stat.S_ISREG(info.st_mode) and os.path.abspath(child) != index_abs:
                found.add((info.st_dev, info.st_ino))
        try:
            diff_children = list((root / "diff").iterdir())
        except TimeoutError: raise
        except OSError:
            diff_children = []
        for child in diff_children:
            inode = _inode_of(child / "diff.json")
            if inode is not None:
                found.add(inode)
                pair.add(inode)
    index_inode = _inode_of(index_path)
    if index_inode is not None and index_inode not in pair:
        found.discard(index_inode)
    return found
def _cas_shaped(path: Path) -> bool:
    data = _read_regular_bytes(path)
    if data is None:
        return False
    head = data[:4096]
    return (_CAS_SCRIPT_MARKER in head
            or any(marker in head for marker in _CAS_MANIFEST_KEYS))
def file_artifact_id(path: str | Path) -> str:
    return _sha256(Path(str(path)).read_bytes())
def _resolved(path: Path) -> Path | None:
    try:
        return path.resolve()
    except TimeoutError: raise
    except (OSError, RuntimeError):
        return None
def _resolved_target(path: Path) -> Path | None:
    return _resolved(path)
def _in_registered_subtree(target: Path, slots: set[Path]) -> bool:
    return any(slot == target or slot in target.parents for slot in slots)
def _has_pair(directory: Any) -> bool:
    root = Path(str(directory))
    return any(path_lexists(root / name) for name in ("repro.py", "manifest.json"))
def _registered_slots() -> set[Path]:
    with _LOCK:
        entries = list(_REGISTRY.values())
        slots: set[Path] = {slot for slot in _SLOTS if _has_pair(slot)}
    for entry in entries:
        for key in ("artifact_path", "manifest_path"):
            value = entry.get(key)
            if not value:
                continue
            parent = Path(str(value)).parent
            if not _has_pair(parent):
                continue
            resolved = _resolved(parent)
            if resolved is not None:
                slots.add(resolved)
    for root in _known_roots():
        try:
            root_info = os.lstat(root)
        except TimeoutError: raise
        except OSError:
            root_info = None
        if root_info is None or not stat.S_ISDIR(root_info.st_mode):
            continue
        try:
            children = list(root.iterdir())
        except TimeoutError: raise
        except OSError:
            children = []
        for child in children:
            try:
                info = os.lstat(child)
            except TimeoutError: raise
            except OSError:
                continue
            if stat.S_ISDIR(info.st_mode) and _has_pair(child):
                resolved = _resolved(child)
                if resolved is not None:
                    slots.add(resolved)
    return slots
def protection_snapshot() -> tuple[set[tuple[int, int]], set[Path]]:
    return _protected_inodes(), _registered_slots()
def _parent_conflicts_with_protected(path: Path) -> bool:
    resolved = _resolved_target(path)
    if resolved is None:
        return True
    root = _resolved(short_root())
    if root is not None and (resolved == root or root in resolved.parents):
        return True
    return _in_registered_subtree(resolved, _registered_slots())
def _path_conflict_reason(script_target: Path, manifest_target: Path) -> str | None:
    root = _resolved(short_root())
    slots = _registered_slots()
    protected = _protected_inodes()
    for path in (script_target, manifest_target):
        if _parent_conflicts_with_protected(path.parent):
            return "output_dir_conflicts_with_registered_artifact"
        try:
            info = os.lstat(path)
        except FileNotFoundError:
            info = None
        except TimeoutError: raise
        except OSError:
            return "output_dir_conflicts_with_registered_artifact"
        if info is not None:
            if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
                return "output_dir_conflicts_with_registered_artifact"
            if (info.st_dev, info.st_ino) in protected:
                return "protected_artifact_target"
            if info.st_nlink > 1 and _cas_shaped(path):
                return "protected_artifact_target"
        resolved = _resolved_target(path)
        if resolved is None:
            return "output_dir_conflicts_with_registered_artifact"
        if root is not None and (resolved == root or root in resolved.parents):
            return "output_dir_conflicts_with_registered_artifact"
        if _in_registered_subtree(resolved, slots):
            return "output_dir_conflicts_with_registered_artifact"
    return None
def _paths_collide(script_target: Path, manifest_target: Path) -> bool:
    try:
        script_name = script_target.name.casefold()
        manifest_name = manifest_target.name.casefold()
        if script_name == "manifest.json":
            return True
        same_parent = (os.path.abspath(script_target.parent)
                       == os.path.abspath(manifest_target.parent))
        folded_parent = (os.path.abspath(script_target.parent).casefold()
                         == os.path.abspath(manifest_target.parent).casefold())
        if script_name == manifest_name and (same_parent or folded_parent):
            return True
        if os.path.abspath(script_target) == os.path.abspath(manifest_target):
            return True
        if os.path.realpath(script_target) == os.path.realpath(manifest_target):
            return True
    except TimeoutError: raise
    except (OSError, TypeError, ValueError):
        return True
    try:
        script_info = os.lstat(script_target)
        manifest_info = os.lstat(manifest_target)
    except FileNotFoundError:
        return False
    except TimeoutError: raise
    except OSError:
        return True
    return ((script_info.st_dev, script_info.st_ino)
            == (manifest_info.st_dev, manifest_info.st_ino))
def _delivery_directory_conflict(directory: str | Path) -> bool:
    target = _resolved(Path(directory))
    if target is None:
        return True
    root = _resolved(short_root())
    if root is not None and (target == root or root in target.parents):
        return True
    if _in_registered_subtree(target, _registered_slots()):
        return True
    manifest = target / "manifest.json"
    data = _read_regular_bytes(manifest)
    if data is None:
        return False
    try:
        loaded = json.loads(data.decode("utf-8"))
    except (ValueError, UnicodeError):
        return False
    return isinstance(loaded, dict) and ( "repro_sha256" in loaded or "script_sha256" in loaded)
def _atomic_write_bytes(target: Path, data: bytes, *, snapshot: tuple[set[tuple[int, int]], set[Path]]
                        | None = None, exclusive: bool = False,
                        installed_out: list[tuple[int, int]] | None = None) -> bool:
    inodes, slots = snapshot if snapshot is not None else protection_snapshot()
    return safe_write_bytes(target, data, protected=inodes | protection_snapshot()[0],
                            forbidden=slots, exclusive=exclusive, installed_out=installed_out,
                            refresh_protected=lambda: protection_snapshot()[0])
def _verify_pair_bytes(script_path: Path, manifest_path: Path,
                       script_bytes: bytes, manifest_bytes: bytes) -> bool:
    delivered_script = _read_regular_bytes(script_path)
    delivered_manifest = _read_regular_bytes(manifest_path)
    if delivered_script is None or delivered_manifest is None:
        return False
    try:
        script_info = os.lstat(script_path)
        manifest_info = os.lstat(manifest_path)
    except TimeoutError: raise
    except OSError:
        return False
    if (not stat.S_ISREG(script_info.st_mode)
            or not stat.S_ISREG(manifest_info.st_mode)):
        return False
    if ((script_info.st_dev, script_info.st_ino)
            == (manifest_info.st_dev, manifest_info.st_ino)):
        return False
    return (delivered_script == script_bytes
            and delivered_manifest == manifest_bytes)
def _prepare_slot(slot_dir: Path) -> str | None:
    root = short_root()
    slots = _registered_slots()
    if not ensure_directory(root, forbidden=slots):
        return "protected_artifact_target"
    try:
        slot_dir.relative_to(root)
    except ValueError:
        return "protected_artifact_target"
    if not ensure_directory(slot_dir, forbidden=slots, allow_slot=slot_dir):
        return "protected_artifact_target"
    for path in (root, slot_dir):
        try:
            info = os.lstat(path)
        except TimeoutError: raise
        except OSError:
            return "artifact_persistence_failed"
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
            return "protected_artifact_target"
    return None
def _slot_state(slot_dir: Path) -> str:
    error = _prepare_slot(slot_dir)
    if error is not None:
        return error
    script_path, manifest_path = slot_dir / "repro.py", slot_dir / "manifest.json"
    script_exists = path_lexists(script_path)
    manifest_exists = path_lexists(manifest_path)
    if not script_exists and not manifest_exists:
        return "clean"
    if not script_exists or not manifest_exists:
        return "protected_artifact_target"
    for path in (script_path, manifest_path):
        try:
            info = os.lstat(path)
        except TimeoutError: raise
        except OSError:
            return "protected_artifact_target"
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
            return "protected_artifact_target"
    return "occupied"
def _write_pair(directory: Path, script: str, manifest: dict[str, Any], *,
                snapshot: tuple[set[tuple[int, int]], set[Path]] | None = None
                ) -> tuple[str, str] | None:
    script_bytes, manifest_bytes = _encode_pair(script, manifest)
    script_path, manifest_path = directory / "repro.py", directory / "manifest.json"
    if _slot_state(directory) != "clean":
        return None
    return _write_caller_pair(script_path, manifest_path, script_bytes, manifest_bytes,
                              snapshot=snapshot, exclusive=True)
def _write_pair_immutable(directory: Path, script: str, manifest: dict[str, Any], identifier: str, *,
                          snapshot: tuple[set[tuple[int, int]], set[Path]]
                          | None = None) -> tuple[tuple[str, str] | None, str | None]:
    script_bytes, manifest_bytes = _encode_pair(script, manifest)
    snapshot = snapshot if snapshot is not None else protection_snapshot()
    state = _slot_state(directory)
    script_path, manifest_path = directory / "repro.py", directory / "manifest.json"
    if state == "clean":
        written = _write_pair(directory, script, manifest, snapshot=snapshot)
        if written is not None:
            return written, None
        state = _slot_state(directory)
        if state != "occupied":
            return None, "artifact_persistence_failed"
    if state == "occupied":
        if _verify_pair_bytes(script_path, manifest_path, script_bytes, manifest_bytes):
            _remember_inodes(script_path, manifest_path)
            return (str(script_path), str(manifest_path)), None
        return None, "artifact_directory_conflict"
    return None, state
class _PairTransaction:
    """Keep prior ordinary leaves until the enclosing pair verification commits."""
    def __init__(self, targets, protected):
        self.installed = {target: [] for target in targets}
        self.backups, self.protected, self.committed = {}, protected, False
    def backup(self):
        for target in self.installed:
            try:
                info = os.lstat(target)
            except FileNotFoundError:
                continue
            inode = (info.st_dev, info.st_ino)
            if not stat.S_ISREG(info.st_mode) or inode in self.protected | _PROTECTED_INODES:
                return False
            backup = target.with_name(f".{target.name}.{os.urandom(16).hex()}.backup")
            self.backups[target] = backup, inode
            os.link(target, backup, follow_symlinks=False)
            if _inode_of(backup) != inode or _inode_of(target) != inode:
                return False
        return True
    def _recover(self, target, primary):
        if target not in self.backups:
            return
        backup, inode = self.backups[target]
        def recover():
            info = os.lstat(backup)
            if not stat.S_ISREG(info.st_mode) or (info.st_dev, info.st_ino) != inode:
                return
            if not self.committed:
                try:
                    os.link(backup, target, follow_symlinks=False)
                except FileExistsError:
                    if _inode_of(target) != inode:
                        os.rename(backup, backup.with_suffix(".rollback"))
                        return  # Preserve the prior leaf without overwriting a foreign occupant.
            os.unlink(backup)  # Verified private hardlink, never a final pathname.
        _retry_cleanup(recover, errno.ENOENT, active_exc=primary)
    def _finish_leaf(self, target, primary):
        with _cleanup_scope(lambda exc: self._recover(target, primary if primary is not None else exc)):
            receipt = self.installed[target]
            if not self.committed:
                _unlink_owned_path(target, receipt[0] if receipt else None,
                                   protected=self.protected, active_exc=primary)
    def finish(self, primary):
        with contextlib.ExitStack() as stack:
            for target in reversed(self.installed):  # ExitStack preserves script-before-manifest rollback.
                stack.enter_context(_cleanup_scope(lambda exc, path=target: self._finish_leaf(
                    path, primary if primary is not None else exc)))
def _write_caller_pair(script_target: Path, manifest_target: Path,
                       script_bytes: bytes, manifest_bytes: bytes, *,
                       snapshot=None, exclusive: bool = False, transaction=None
                       ) -> tuple[str, str] | None:
    """One ownership transaction for both exclusive CAS and caller mirrors."""
    snapshot = snapshot if snapshot is not None else protection_snapshot()
    tx = transaction or _PairTransaction((script_target, manifest_target), snapshot[0])
    with _cleanup_scope(tx.finish if transaction is None else lambda exc: None):
        try:
            if not exclusive and not tx.backup():
                return None
        except TimeoutError: raise
        except OSError:
            return None
        for target, data in ((script_target, script_bytes), (manifest_target, manifest_bytes)):
            if not _atomic_write_bytes(target, data, snapshot=snapshot,
                                       exclusive=exclusive, installed_out=tx.installed[target]):
                return None
        if not _verify_pair_bytes(script_target, manifest_target, script_bytes, manifest_bytes):
            return None
        if exclusive:
            _remember_inodes(script_target, manifest_target)
        tx.committed = transaction is None
        return str(script_target), str(manifest_target)
def _index_path() -> Path:
    return short_root() / _INDEX_NAME
def _record_index(entry: dict[str, Any]) -> bool:
    path = _index_path()
    try:
        existing: dict[str, Any] = {}
        raw = _read_regular_bytes(path)
        if raw is not None:
            loaded = json.loads(raw.decode("utf-8"))
            existing = loaded if isinstance(loaded, dict) else {}
        existing[entry["artifact_id"]] = entry
        data = (json.dumps(existing, indent=2, sort_keys=True)
                + "\n").encode("utf-8")
        if _atomic_write_bytes(path, data):
            return True
        return _atomic_write_bytes(path, data)
    except TimeoutError: raise
    except (OSError, ValueError, UnicodeError):
        return False
def _lookup_index(identifier: str) -> dict[str, Any] | None:
    try:
        raw = _read_regular_bytes(_index_path())
        if raw is None:
            return None
        loaded = json.loads(raw.decode("utf-8"))
    except TimeoutError: raise
    except (OSError, ValueError, UnicodeError):
        return None
    if not isinstance(loaded, dict):
        return None
    entry = loaded.get(identifier)
    return entry if isinstance(entry, dict) else None
def _lookup_scan(identifier: str) -> dict[str, Any] | None:
    try:
        directories = list(short_root().iterdir())
    except TimeoutError: raise
    except OSError:
        return None
    for directory in directories:
        manifest_path = directory / "manifest.json"
        script_path = directory / "repro.py"
        manifest_data = _read_regular_bytes(manifest_path)
        if manifest_data is None:
            continue
        try:
            manifest = json.loads(manifest_data.decode("utf-8"))
        except (ValueError, UnicodeError):
            continue
        if isinstance(manifest, dict) and manifest.get("repro_sha256") == identifier:
            return {"artifact_id": identifier, "artifact_path": str(script_path),
                    "manifest_path": str(manifest_path),
                    "script_sha256": identifier, "resolved": True,
                    "retrievable": _readable(script_path)
                    and _readable(manifest_path)}
    return None
def _register(entry: dict[str, Any]) -> bool:
    with _LOCK:
        _REGISTRY[entry["artifact_id"]] = dict(entry)
        for key in ("artifact_path", "manifest_path"):
            value = entry.get(key)
            if not value:
                continue
            resolved = _resolved(Path(str(value)).parent)
            if resolved is not None:
                _SLOTS.add(resolved)
    _remember_inodes(entry.get("artifact_path"), entry.get("manifest_path"))
    return _record_index(dict(entry))
def _verify_entry(entry: dict[str, Any], identifier: str) -> tuple[dict[str, Any] | None, str | None]:
    script_path = entry.get("artifact_path")
    manifest_path = entry.get("manifest_path")
    if not (_readable(script_path) and _readable(manifest_path)):
        return None, "artifact_not_retrievable"
    try:
        actual = file_artifact_id(script_path)
        loaded = json.loads(Path(str(manifest_path)).read_text(encoding="utf-8"))
    except TimeoutError: raise
    except (OSError, ValueError, UnicodeError):
        return None, "artifact_integrity_mismatch"
    if not isinstance(loaded, dict) or actual != identifier:
        return None, "artifact_integrity_mismatch"
    declared = loaded.get("script_sha256")
    legacy = loaded.get("repro_sha256")
    if (declared is not None and declared != identifier) or (
            legacy is not None and legacy != identifier) or (
            declared is None and legacy is None):
        return None, "artifact_integrity_mismatch"
    return {"schema": "mindie-repro-artifact-resolution/1", "artifact_id": identifier, "resolved": True,
            "artifact_path": script_path, "manifest_path": manifest_path,
            "script_sha256": actual, "retrievable": True}, None
def resolve_repro_artifact(artifact_id_value: str) -> dict[str, Any]:
    """Resolve a ``sha256:`` handle and verify the bytes it names."""
    identifier = str(artifact_id_value or "")
    with _LOCK:
        entry = _REGISTRY.get(identifier)
    if entry is None:
        entry = _lookup_index(identifier)
    if entry is None:
        entry = _lookup_scan(identifier)
    if entry is None:
        return {"schema": "mindie-repro-artifact-resolution/1", "artifact_id": identifier, "resolved": False,
                "retrievable": False, "error": "artifact_not_found"}
    verified, error = _verify_entry(entry, identifier)
    if verified is None:
        return {"schema": "mindie-repro-artifact-resolution/1", "artifact_id": identifier, "resolved": False,
                "retrievable": False, "error": error}
    return verified
def _stage_failure(identifier: str, status: str, error: str, *,
                   conflict: bool = False, protected: bool = False,
                   manifest_sha256: str | None = None) -> dict[str, Any]:
    return {
        "artifact_id": identifier, "script_sha256": identifier,
        "manifest_sha256": manifest_sha256, "status": status, "error": error,
        "immutable_conflict": conflict, "protected_artifact_target": protected,
        "artifact_path": None, "manifest_path": None,
        "short_artifact_path": None, "short_manifest_path": None,
        "requested_artifact_path": None, "requested_manifest_path": None,
        "retrievable": False,
    }
def stage_artifacts(script: str, manifest: dict[str, Any], *, output_dir: str | Path | None = None,
                    output_path: str | Path | None = None) -> dict[str, Any]:
    """Write the short-root copy, mirror a caller path, and register the id."""
    from .repro_snapshot import snapshot as container_snapshot
    manifest = container_snapshot(manifest)
    identifier = artifact_id(script)
    script_bytes, manifest_bytes = _encode_pair(script, manifest)
    manifest_sha256 = _sha256(manifest_bytes)
    digest = identifier.split(":", 1)[-1]
    script_target = manifest_target = None
    requested_directory = None
    if output_dir is not None:
        requested_directory = Path(output_dir)
        script_target = requested_directory / "repro.py"
        manifest_target = requested_directory / "manifest.json"
    elif output_path is not None:
        script_target = Path(output_path)
        manifest_target = script_target.with_name("manifest.json")
        requested_directory = script_target.parent
    if requested_directory is not None and script_target is not None \
            and manifest_target is not None:
        reason = _path_conflict_reason(script_target, manifest_target)
        if reason == "protected_artifact_target":
            return _stage_failure(identifier, "delivery_failed", "protected_artifact_target", protected=True,
                                  manifest_sha256=manifest_sha256)
        if reason is not None or _delivery_directory_conflict(requested_directory):
            return _stage_failure(identifier, "delivery_blocked",
                "output_dir_conflicts_with_registered_artifact",
                conflict=True, manifest_sha256=manifest_sha256)
    if (script_target is not None and manifest_target is not None
            and _paths_collide(script_target, manifest_target)):
        return _stage_failure(identifier, "delivery_blocked", "colliding_output_paths", conflict=True,
                              manifest_sha256=manifest_sha256)
    snapshot = protection_snapshot()
    short_dir = short_root() / digest[:12]
    short_paths, short_error = _write_pair_immutable(short_dir, script, manifest, identifier, snapshot=snapshot)
    if short_error is not None:
        if short_error == "artifact_directory_conflict":
            return _stage_failure(identifier, "delivery_blocked", short_error, conflict=True,
                                  manifest_sha256=manifest_sha256)
        return _stage_failure(identifier, "delivery_failed", "artifact_persistence_failed",
            protected=short_error == "protected_artifact_target",
            manifest_sha256=manifest_sha256)
    transaction = _PairTransaction((script_target, manifest_target), snapshot[0]) if script_target else None
    with _cleanup_scope(transaction.finish if transaction else lambda exc: None):
        requested: tuple[str, str] | None = None
        if script_target is not None and manifest_target is not None:
            requested = _write_caller_pair(script_target, manifest_target,
                                           script_bytes, manifest_bytes, transaction=transaction)
            if requested is None:
                return _stage_failure(identifier, "delivery_failed", "artifact_write_failed",
                                      manifest_sha256=manifest_sha256)
        chosen = requested or short_paths
        if not chosen:
            return _stage_failure(identifier, "delivery_failed", "artifact_write_failed",
                                  manifest_sha256=manifest_sha256)
        if not _verify_pair_bytes(Path(chosen[0]), Path(chosen[1]), script_bytes, manifest_bytes):
            return _stage_failure(identifier, "delivery_failed", "artifact_digest_mismatch",
                                  manifest_sha256=manifest_sha256)
        if transaction:
            transaction.committed = True
    result = {
        "artifact_id": identifier, "script_sha256": identifier,
        "manifest_sha256": manifest_sha256, "status": "delivered",
        "error": None, "immutable_conflict": False,
        "protected_artifact_target": False,
        "artifact_path": chosen[0], "manifest_path": chosen[1],
        "short_artifact_path": short_paths[0] if short_paths else None,
        "short_manifest_path": short_paths[1] if short_paths else None,
        "requested_artifact_path": requested[0] if requested else None,
        "requested_manifest_path": requested[1] if requested else None,
        "retrievable": True,
    }
    indexed = _register({"artifact_id": identifier,
                         "artifact_path": result["short_artifact_path"] or chosen[0],
                         "manifest_path": result["short_manifest_path"] or chosen[1],
                         "script_sha256": identifier})
    result["index_persisted"] = indexed
    result["index_warning"] = None if indexed else "index_persistence_failed"
    if not indexed:
        result["status"] = "delivery_failed"
        result["error"] = "index_persistence_failed"
        result["retrievable"] = False
    return result
